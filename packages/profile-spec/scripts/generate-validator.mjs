import { readFile, writeFile } from 'node:fs/promises';

import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schemaUrl = new URL('../schema/profile-spec-v1.schema.json', import.meta.url);
const outputUrl = new URL('../src/profile-spec-validator.generated.ts', import.meta.url);
const schema = JSON.parse(await readFile(schemaUrl, 'utf8'));
const ajv = new Ajv2020({
  allErrors: true,
  allowUnionTypes: true,
  strict: true,
  validateFormats: false,
  code: {
    esm: true,
    source: true,
    lines: true,
  },
});
const validate = ajv.compile(schema);
const source = standaloneCode(ajv, validate);
const banner = `/* This file is generated by packages/profile-spec/scripts/generate-validator.mjs. */\n/* Do not edit manually. Regenerate after changing the ProfileSpec JSON schema. */\n// @ts-nocheck\n`;
await writeFile(outputUrl, `${banner}${source}\n`, 'utf8');
console.log(`Generated CSP-safe ProfileSpec validator: ${outputUrl.pathname}`);
